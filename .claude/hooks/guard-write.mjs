// PreToolUse guard for Edit/Write/NotebookEdit: enforces the worktree and migration rules from AGENTS.md and infra/AGENTS.md.
import { execFileSync } from "node:child_process"
import { existsSync } from "node:fs"
import { dirname, relative } from "node:path"
import { decide, readHookInput } from "./hook-io.mjs"

const { tool_name: tool, tool_input: input = {} } = readHookInput()
const file = input.file_path ?? input.notebook_path
if (!file) process.exit(0)

function git(cwd, ...args) {
  try {
    return execFileSync("git", ["-C", cwd, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim()
  } catch {
    return null
  }
}

let dir = dirname(file)
while (!existsSync(dir)) dir = dirname(dir)
const root = git(dir, "rev-parse", "--show-toplevel")
if (!root) process.exit(0)
const path = relative(root, file)

// Tracked files change in a worktree on a feature branch, never in the main checkout (AGENTS.md "Worktrees and `.agents/`").
// Exceptions: the release skill's CHANGELOG commit, and agent memory, which the harness writes under the session's start directory.
const onMain = git(root, "branch", "--show-current") === "main"
const ignored = git(root, "check-ignore", "-q", file) !== null
if (onMain && !ignored && !/^CHANGELOG(\.[\w-]+)?\.md$/.test(path) && !path.startsWith(".claude/agent-memory/")) {
  decide("deny", `${path} is in a checkout on \`main\`. Create a worktree first (feature skill, "Before the first write") and call EnterWorktree, then edit the file there.`)
}

// Migrations are generated by drizzle-kit, never hand-written (infra/AGENTS.md "Migrations"). Editing a generated .sql (e.g. a --custom backfill) is fine.
if (path.startsWith("infra/migrations/")) {
  const regenerate = "Generate migrations with `npm run migrations:create` (add `-- --custom --name <name>` for a hand-filled SQL migration); never hand-write the file (infra/AGENTS.md \"Migrations\")."
  if (/\.sql$/.test(path) && !existsSync(file)) decide("deny", regenerate)
  if (/^infra\/migrations\/meta\/.*_snapshot\.json$/.test(path)) decide("deny", `Snapshots are generated by drizzle-kit. ${regenerate}`)
  if (path === "infra/migrations/meta/_journal.json") {
    if (tool !== "Edit") decide("deny", `The journal is generated by drizzle-kit. ${regenerate}`)
    decide("ask", "Only the `tag` of a regenerated migration may be edited in _journal.json (infra/AGENTS.md \"Migrations\"). Confirm this edit.")
  }
}
